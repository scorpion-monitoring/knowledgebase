// Writes the Vale rules that come from src/data/terms.ts. CI runs `pnpm vale:gen --check` and fails
// when the committed files are stale.

import { mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { bannedWords, forbiddenWording, terminologyRoleNames, terms } from '../src/data/terms';
import { modules } from '../src/data/modules';

const root = fileURLToPath(new URL('..', import.meta.url));
const HEADER = '# GENERATED by scripts/gen-vale.ts from src/data/terms.ts. Do not edit by hand.\n';

const q = (s: string) => `'${s.replaceAll("'", "''")}'`;

export function generate(): Record<string, string> {
  const swap = new Map<string, string>();
  for (const t of terms) for (const a of t.avoid ?? []) swap.set(a, t.preferred);
  for (const w of forbiddenWording) swap.set(w.avoid, w.use);

  const substitutions = `${HEADER}extends: substitution
message: "Use '%s' instead of '%s'."
level: error
ignorecase: false
swap:
${[...swap].map(([a, b]) => `  ${q(a)}: ${q(b)}`).join('\n')}
`;

  const banned = `${HEADER}extends: existence
message: "Do not use '%s'."
level: error
ignorecase: true
tokens:
${bannedWords.map((w) => `  - '\\b${w}\\b'`).join('\n')}
`;

  // Preferred spellings that other Vale rules must accept. 'Scorpion' is deliberately absent: Vale
  // lets an accepted word override matches, which would silence the Terminology rule.
  const accept = `${[
    ...new Set(
      terms.map((t) => t.preferred.replace(/\s*\(.*\)$/, '')).filter((p) => /[A-Z]/.test(p)),
    ),
    'OIDC',
    'KPI',
    'KPIs',
  ]
    .sort()
    .join('\n')}\n`;

  const names = [
    ...modules.map((m) => m.id.replaceAll('.', '\\.')),
    ...terminologyRoleNames,
    'Scorpion',
  ];
  const terminology = `${HEADER}extends: existence
message: "'%s' is tool-specific. Terminology pages are tool-agnostic: move the mapping to start/scorpion-terms."
level: error
scope: raw
ignorecase: false
tokens:
${names.map((n) => `  - '\\b${n}\\b'`).join('\n')}
`;

  return {
    'styles/Scorpion/Substitutions.yml': substitutions,
    'styles/Scorpion/BannedWords.yml': banned,
    'styles/config/vocabularies/Scorpion/accept.txt': accept,
    'styles/Terminology/NoToolNames.yml': terminology,
  };
}

const check = process.argv.includes('--check');
let stale = 0;
for (const [rel, content] of Object.entries(generate())) {
  const path = join(root, rel);
  if (check) {
    if (!existsSync(path) || readFileSync(path, 'utf8') !== content) {
      console.error(`stale: ${rel} (run pnpm vale:gen)`);
      stale++;
    }
  } else {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
  }
}
if (stale > 0) process.exit(1);
